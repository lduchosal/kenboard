"""Unit tests for the dependency supply-chain gates (ken #1241, #1242).

Covers the pure logic of scripts/runtime_deps.py (requirements parsing),
scripts/guarddog_gate.py (blocking rules, allowlist) and scripts/dep_scorecard.py
(history snapshots, divergence detection, scoreboard rendering). No network.
"""

import datetime
import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

SCRIPTS = Path(__file__).resolve().parents[2] / "scripts"


def _load(name: str) -> ModuleType:
    """Import a script module by path (scripts/ is not a package)."""
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


rd = _load("runtime_deps")
gd = _load("guarddog_gate")
sc = _load("dep_scorecard")


# -- runtime_deps -------------------------------------------------------------


def test_parse_pins_canonicalises_and_skips_comments() -> None:
    text = (
        "# generated by PDM\n"
        "PyYAML==6.0.4\n"
        "pymysql[rsa]==1.2.4 ; python_version >= '3.11'\n"
        "typing_extensions==4.16.0 \\\n"
        "-e file:///src\n"
    )
    assert rd.parse_pins(text) == {
        "pyyaml": "6.0.4",
        "pymysql": "1.2.4",
        "typing-extensions": "4.16.0",
    }


def test_unconditional_requirements_drop_extras() -> None:
    reqs = ["pip>=24.2", 'gevent>=24; extra == "gevent"', "Foo_Bar; python_version<'4'"]
    assert rd.unconditional_requirements(reqs) == ["pip", "foo-bar"]
    assert rd.unconditional_requirements(None) == []


# -- guarddog_gate ------------------------------------------------------------


RAW = {
    "typosquatting": None,
    "potentially_compromised_email_domain": "maintainer domain expired",
    "capability-network-outbound": [{"location": "pkg/net.py:3", "message": "m"}],
    "threat-npm-preinstall-script": [{"location": "x:1", "message": "m"}],
    "threat-filesystem-read": [
        {
            "location": "dotenv/main.py:71",
            "message": "sensitive file",
            "code": 'def f():\n  return ".env"\n',
            "match": '".env"',
        },
        {"location": "dotenv/cli.py:34", "message": "sensitive file", "code": ""},
    ],
}


def test_findings_keep_threat_and_metadata_rules_only() -> None:
    found = gd.findings_of("python-dotenv", "1.2.4", RAW)
    assert [(f.rule, f.file) for f in found] == [
        ("potentially_compromised_email_domain", ""),
        ("threat-filesystem-read", "dotenv/main.py"),
        ("threat-filesystem-read", "dotenv/cli.py"),
    ]
    assert found[1].code == '".env"'


def test_bundled_binary_gives_one_finding_per_file() -> None:
    sha = "ab" * 32
    raw = {
        "bundled_binary": f"Binary file/s detected in package:\n{sha}: t64.exe (exe)\n{sha}: w32.exe (exe)"
    }
    found = gd.findings_of("pip", "26.3", raw)
    assert [(f.rule, f.file) for f in found] == [
        ("bundled_binary", "t64.exe"),
        ("bundled_binary", "w32.exe"),
    ]


def test_allowlist_matches_files_exactly_and_tracks_usage() -> None:
    found = gd.findings_of("python-dotenv", "1.2.4", RAW)
    allow = [
        gd.Allow(
            "python-dotenv",
            "threat-filesystem-read",
            frozenset({"dotenv/main.py"}),
            "r",
        ),
        gd.Allow("flask", "threat-filesystem-read", frozenset(), "r"),
    ]
    blocking, allowed = gd.apply_allowlist(found, allow)
    assert allowed == 1
    assert {(f.rule, f.file) for f in blocking} == {
        ("potentially_compromised_email_domain", ""),
        ("threat-filesystem-read", "dotenv/cli.py"),
    }
    assert [a.used for a in allow] == [True, False]


def test_allowlist_requires_a_reason(tmp_path: Path) -> None:
    conf = tmp_path / "pyproject.toml"
    conf.write_text(
        '[[tool.kenboard.guarddog.allow]]\npackage = "Flask"\nrule = "threat-x"\nreason = ""\n'
    )
    with pytest.raises(SystemExit, match="without a reason"):
        gd.load_allowlist(conf)
    conf.write_text(
        '[[tool.kenboard.guarddog.allow]]\npackage = "Flask"\nrule = "threat-x"\nreason = "ok"\n'
    )
    (entry,) = gd.load_allowlist(conf)
    assert entry.package == "flask"
    assert entry.files == frozenset()


def test_project_allowlist_is_valid() -> None:
    """Every entry shipped in pyproject.toml parses and carries a reason."""
    assert all(entry.reason for entry in gd.load_allowlist())


# -- dep_scorecard ------------------------------------------------------------


def _row(package: str, **fields: str) -> dict[str, str]:
    """Build a scorecard row with healthy defaults."""
    row = dict.fromkeys(sc.FIELDS, "")
    row |= {
        "snapshot": "s",
        "package": package,
        "version": "1.0",
        "repo": f"github.com/x/{package}",
        "attested": "yes",
        "score": "7.0",
        "scorecard_date": "2026-11-23",
        "scorecard_source": "openssf",
        "Maintained": "10",
        "Code-Review": "8",
        "Dangerous-Workflow": "10",
    }
    return row | fields


def test_no_divergence_on_plain_version_bump() -> None:
    warnings, notes = sc.divergences([_row("a")], [_row("a", version="2.0")])
    assert (warnings, notes) == ([], [])


@pytest.mark.parametrize(
    ("change", "expected"),
    [
        ({"score": "5.9"}, "score dropped 7.0 → 5.9"),
        ({"repo": "github.com/evil/a"}, "source repo changed"),
        ({"attested": "no"}, "lost its PyPI publish attestation"),
        ({"Maintained": "0"}, "Maintained fell to 0"),
        ({"score": ""}, "scorecard no longer available"),
    ],
)
def test_divergences_flag_each_signal(change: dict[str, str], expected: str) -> None:
    warnings, _ = sc.divergences([_row("a")], [_row("a", **change)])
    assert len(warnings) == 1
    assert expected in warnings[0]


def test_small_score_drop_is_not_a_divergence() -> None:
    warnings, _ = sc.divergences([_row("a")], [_row("a", score="6.1")])
    assert warnings == []


def test_new_and_removed_packages() -> None:
    warnings, notes = sc.divergences(
        [_row("a"), _row("gone")], [_row("a"), _row("b", score="")]
    )
    assert warnings == [
        "new runtime dependency b==1.0 — score no scorecard (github.com/x/b, attested: yes)"
    ]
    assert notes == ["gone left the runtime closure"]


def test_same_state_ignores_snapshot_and_scorecard_date() -> None:
    old = [_row("a", snapshot="t1", scorecard_date="2026-11-16")]
    assert sc.same_state(old, [_row("a", snapshot="t2", scorecard_date="2026-11-23")])
    assert not sc.same_state(old, [_row("a", version="2.0")])


def test_history_roundtrip_appends_one_pending_snapshot() -> None:
    first = sc.render_history("", [_row("a", snapshot="t1")])
    second = sc.render_history(first, [_row("a", snapshot="t2", version="2.0")])
    assert second.startswith(first)
    snapshots = sc.parse_history(second)
    assert [snap for snap, _ in snapshots] == ["t1", "t2"]
    assert snapshots[1][1][0]["version"] == "2.0"


def test_board_lists_divergences_and_sorts_by_score() -> None:
    history = [
        ("t1", [_row("a"), _row("b", score="8.0")]),
        (
            "t2",
            [
                _row("a", score="4.0", scorecard_date="2026-01-01"),
                _row("b", score="8.0"),
            ],
        ),
    ]
    board = sc.render_board(history, datetime.date(2026, 11, 25))
    assert "⚠ a: score dropped 7.0 → 4.0" in board
    assert board.index("| a |") < board.index("| b |")
    assert "2026-01-01 (ancien)" in board


def test_board_first_snapshot() -> None:
    board = sc.render_board(
        [("t1", [_row("a", score="")])], datetime.date(2026, 11, 25)
    )
    assert "Premier snapshot" in board
    assert "aucun scorecard disponible" in board


def test_board_flags_deps_dev_fallback_and_stale_separately() -> None:
    today = datetime.date(2026, 11, 26)
    fallback = _row("a", scorecard_source="deps.dev", scorecard_date="2026-08-24")
    old = _row("b", scorecard_date="2023-11-20")
    fresh_fallback = _row("c", scorecard_source="deps.dev")
    board = sc.render_board([("t1", [fallback, old, fresh_fallback])], today)
    assert "| 2026-08-24 (deps.dev, ancien) |" in board
    assert "| 2023-11-20 (ancien) |" in board
    assert "| 2026-11-23 (deps.dev) |" in board


def test_board_lists_blind_spots() -> None:
    rows = [
        _row("covered"),
        _row("authlib", score=""),
        _row("yoyo", score="", repo="", attested="no"),
    ]
    board = sc.render_board([("t1", rows)], datetime.date(2026, 11, 26))
    section = board.split("## Angles morts", 1)[1]
    assert "- authlib 1.0 — github.com/x/authlib, attestation PyPI" in section
    assert (
        "- yoyo 1.0 — dépôt source inconnu de deps.dev, sans attestation PyPI"
        in section
    )
    assert "covered" not in section


def test_board_without_blind_spot_has_no_section() -> None:
    board = sc.render_board([("t1", [_row("a")])], datetime.date(2026, 11, 26))
    assert "Angles morts" not in board
